const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const context = vm.createContext({});
vm.runInContext(fs.readFileSync('config/window-state.js', 'utf8'), context);
const workspaces = [{id:1,output:'A',is_active:true},{id:2,output:'A',is_active:false},{id:3,output:'B',is_active:true}];
const check = (windows, output='A', overview=false) => context.fullscreenOn(windows,workspaces,output,1536,864,overview);
const win = (workspace, width, height) => ({workspace_id:workspace,layout:{window_size:[width,height]}});
assert.equal(check([win(1,1536,864)]),true);
assert.equal(check([win(1,1525,830)]),false);
assert.equal(check([win(1,1536,830)]),false);
assert.equal(check([win(2,1536,864)]),false);
assert.equal(check([win(3,1536,864)]),false);
assert.equal(check([win(3,1536,864)],'B'),true);
assert.equal(check([win(1,1536,864)],'A',true),false);
assert.equal(check([{workspace_id:1,is_fullscreen:true}]),true);
assert.equal(check([{...win(1,1536,864),is_fullscreen:false}]),false);
assert.equal(check([{workspace_id:1}]),false);
assert.equal(check([]),false);
console.log('Fullscreen: geometry, maximized windows, inactive workspaces, outputs and overview: OK');
