const fs = require("fs");
const path = require("path");
const assert = require("assert/strict");
const code = fs.readFileSync(path.join(__dirname, "../config/countdown.js"), "utf8").replace(/^\.pragma library\s*$/m, "");
const timer = new Function(code + "\nreturn { idle, start, pomodoro, advance, pause, resume, restore, remaining, format };")();
assert.equal(timer.start(0, 0), null);
assert.equal(timer.start(NaN, 0), null);
assert.equal(timer.start(86401, 0), null);
let state = timer.start(60, 1000);
assert.equal(timer.remaining(state, 21000), 40000);
state = timer.pause(state, 21000);
assert.equal(timer.remaining(state, 1000000), 40000);
state = timer.restore(JSON.parse(JSON.stringify(state)));
state = timer.resume(state, 1000000);
assert.equal(timer.remaining(state, 1010000), 30000);
let next = timer.advance(state, 1040000);
assert.equal(next.event, "finished");
assert.equal(next.state.running, false);
assert.equal(timer.advance(next.state, 9999999).event, "");
state = timer.pomodoro(1500, 300, 900, true, 0);
for (let cycle = 1; cycle <= 4; cycle++) {
    next = timer.advance(state, state.deadline);
    assert.equal(next.event, cycle === 4 ? "longRest" : "rest");
    assert.equal(next.state.completed, cycle);
    assert.equal(next.state.total, cycle === 4 ? 900000 : 300000);
    state = timer.advance(next.state, next.state.deadline).state;
    assert.equal(state.phase, "work");
}
state = timer.pomodoro(60, 10, 20, true, 0);
next = timer.advance(state, 86400000);
assert.equal(next.state.completed, 1, "Sleep must not count as multiple completed work intervals");
assert.equal(next.state.deadline, 86410000);
state = timer.pomodoro(60, 10, 20, false, 0);
next = timer.advance(state, 60000);
assert.equal(next.state.running, false);
assert.equal(next.state.remaining, 10000);
assert.equal(timer.resume(next.state, 90000).deadline, 100000);
assert.equal(timer.restore({version: 1, phase: "work"}).phase, "idle");
assert.equal(timer.restore({...timer.start(60, 0), deadline: NaN}).phase, "idle");
assert.equal(timer.restore({...timer.start(60, 0), phase: "work"}).phase, "idle");
assert.equal(timer.format(59999), "1:00");
assert.equal(timer.format(3600000), "1:00:00");
assert.equal(timer.format(0), "0:00");
console.log("Countdown pause/resume, restore, Pomodoro cycles and suspend handling: OK");
